const assert = require('node:assert/strict');
const { History, readBook, validateDraft } = require('./editor-state.js');
const { shift, serialize, parse } = require('./lyrics-core.js');
const first = { version: 1, name: '曲A', selected: 0, rows: [{ seconds: 0, text: '最初' }, { seconds: 2, text: '次' }, { seconds: null, text: '未設定' }] };
const history = new History();
history.push(first);
const stamped = structuredClone(first); stamped.rows[2].seconds = 5;
history.push(stamped);
const removed = structuredClone(stamped); removed.rows.splice(1, 1);
assert.deepEqual(history.undo(removed), stamped);
assert.deepEqual(history.undo(stamped), first);
assert.deepEqual(history.redo(first), stamped);
history.push(stamped);
assert.equal(history.redo(removed), null, 'editing after undo clears redo');
const moved = shift(first.rows, -0.5);
assert.deepEqual(moved.map(r => r.seconds), [0, 1.5, null]);
assert.equal(first.rows[1].seconds, 2, 'shift does not mutate the previous history state');
assert.deepEqual(shift(first.rows, 0.2, 1).map(r => r.seconds), [0, 2.2, null]);
assert.throws(() => shift(first.rows, Infinity));
assert.deepEqual(parse(serialize(shift(stamped.rows, 0.2))).map(r => r.seconds), [0.2, 2.2, 5.2]);
const migrated = readBook(first, () => 'new-id');
assert.equal(migrated.drafts[0].name, '曲A');
const book = { version: 2, activeID: 'b', drafts: [{ id: 'a', ...first }, { id: 'b', version: 1, name: '曲B', rows: [{ seconds: 10, text: '別の歌詞' }] }] };
const restored = readBook(JSON.parse(JSON.stringify(book)), () => 'generated');
assert.equal(restored.activeID, 'b');
assert.deepEqual(restored.drafts[0].rows, first.rows);
assert.equal(restored.drafts[1].rows[0].seconds, 10);
assert.throws(() => validateDraft({ ...first, rows: [{ seconds: -1, text: 'bad' }] }));
assert.throws(() => readBook({ version: 2, drafts: [] }, () => 'id'));
console.log('Editor state checks passed: undo/redo, non-destructive offsets, multi-song drafts and migration.');
